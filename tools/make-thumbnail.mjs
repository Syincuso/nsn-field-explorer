// Usage: node tools/make-thumbnail.mjs [output.png]   (default store/images/youtube-thumbnail-1280x720.png)
// Draws the YouTube thumbnail for the reviewer video, in the style of the store marquee: the extension's logo and
// name on rich black, a tagline, a "Works with NetSuite Next" badge, the panel (cropped from store/images/01-body.png) and the gold bar at the bottom.
// Fonts are Poppins and Open Sans: from <SYINCUSO_SITE>/teaser/fonts when that variable points at the syincuso.com
// site, else whatever is installed (system fonts if neither is). Playwright is loaded like the tests (NSFE_PLAYWRIGHT_DIR
// overrides it).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.resolve(process.argv[2] || path.join(ROOT, 'store', 'images', 'youtube-thumbnail-1280x720.png'));
const PW_DIR = process.env.NSFE_PLAYWRIGHT_DIR || ROOT;
const FONTS = process.env.SYINCUSO_SITE ? path.join(process.env.SYINCUSO_SITE, 'teaser', 'fonts') : '';
const { chromium } = createRequire(path.join(PW_DIR, 'package.json'))('playwright');
const url = p => pathToFileURL(p).href;
const font = f => url(path.join(FONTS, f));
const FACES = FONTS && fs.existsSync(FONTS) ? `
@font-face{font-family:Poppins;font-weight:700;src:url(${font('poppins-700-latin.woff2')})}
@font-face{font-family:Poppins;font-weight:600;src:url(${font('poppins-600-latin.woff2')})}
@font-face{font-family:"Open Sans";src:url(${font('open-sans-latin.woff2')})}` : '';
if (!FACES) console.log('Fonts: ' + (FONTS ? FONTS + ' not found' : 'SYINCUSO_SITE not set') + ', using installed fonts');

const HTML = `<!doctype html><html><head><meta charset="utf-8"><style>${FACES}
*{box-sizing:border-box}html,body{margin:0}
body{width:1280px;height:720px;overflow:hidden;position:relative;background:#0b0b0b;color:#fff;font-family:"Open Sans",sans-serif}
.left{position:absolute;left:64px;top:84px;width:600px}
.brand{display:flex;align-items:center;gap:26px}
.brand img{width:178px;height:178px}
h1{margin:0;font:700 76px/1.02 Poppins,sans-serif;letter-spacing:-.01em}
.tag{margin:38px 0 0;font-size:38px;line-height:1.3;color:#e8e8e8}
.tag b{color:#fff;font-weight:700}
.next{display:inline-flex;align-items:center;gap:12px;margin-top:28px;padding:10px 22px 10px 16px;border-radius:999px;background:#c9a227;color:#0b0b0b;font:700 30px Poppins,sans-serif}
.next svg{width:30px;height:30px;fill:none;stroke:#0b0b0b;stroke-width:3.2;stroke-linecap:round;stroke-linejoin:round}
.meta{margin-top:24px;font:600 25px Poppins,sans-serif;color:#c9a227;letter-spacing:.01em}
.shot{position:absolute;left:676px;top:96px;width:790px;height:676px;transform:scale(.8);transform-origin:0 0;border-radius:12px;
 background:url(${url(path.join(ROOT, 'store', 'images', '01-body.png'))}) -470px -62px/1280px 800px;box-shadow:0 18px 60px rgba(0,0,0,.6),0 0 0 1px rgba(255,255,255,.08)}
.bar{position:absolute;left:0;right:0;bottom:0;height:14px;background:#c9a227}
</style></head><body>
<div class="left">
  <div class="brand"><img src="${url(path.join(ROOT, 'store', 'images', 'logo-300.png'))}" alt=""><h1>NSN Field<br>Explorer</h1></div>
  <p class="tag"><b>Every field ID</b> on any NetSuite record, in one click.</p>
  <div class="next"><svg viewBox="0 0 24 24"><path d="M5 12.5l4.5 4.5L19 7.5"/></svg>Works with NetSuite Next</div>
  <div class="meta">Read-only &middot; Chrome, Edge &amp; Firefox</div>
</div>
<div class="shot"></div>
<div class="bar"></div>
</body></html>`;

const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'nsfe-thumb-')), 'thumb.html');
fs.writeFileSync(tmp, HTML);
await page.goto(url(tmp));
await page.evaluate(() => document.fonts.ready);
fs.mkdirSync(path.dirname(OUT), { recursive: true });
await page.screenshot({ path: OUT });
await browser.close();
fs.rmSync(path.dirname(tmp), { recursive: true, force: true });
console.log('Thumbnail: ' + OUT);

