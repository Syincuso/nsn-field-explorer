// Usage: node tools/demo.mjs [port]   (default 8642)
// Serves the demo vendor bill in store/demo/ on http://127.0.0.1:<port>/ for the reviewer video and store
// images: a local mock of a NetSuite Next record page with invented data, served with a NetSuite-style
// Content-Security-Policy (no inline scripts or styles). Load the unpacked extension (the extension folder),
// open the URL and click the toolbar button. Links to NetSuite pages (/app/...) get a stand-in page.
// tools/record-video.mjs imports startDemo to serve the same page while it records.
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEMO = path.join(ROOT, 'store', 'demo');
const CSP = "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:";
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };

// Starts the server; resolves with it once it listens (port 0 picks a free port).
export function startDemo(port) {
  const server = http.createServer((req, res) => {
    let url = decodeURIComponent(req.url.split('?')[0]);
    if (url === '/favicon.ico') { res.writeHead(204); return res.end(); }
    if (url === '/') url = '/index.html';
    if (url.startsWith('/app/')) url = '/app.html';
    const p = path.resolve(DEMO, '.' + url);
    if (!p.startsWith(DEMO + path.sep) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) { res.writeHead(404); return res.end('Not found'); }
    res.writeHead(200, { 'Content-Type': TYPES[path.extname(p)] || 'application/octet-stream', 'Content-Security-Policy': CSP, 'Cache-Control': 'no-store' });
    fs.createReadStream(p).pipe(res);
  });
  return new Promise(resolve => server.listen(port, '127.0.0.1', () => resolve(server)));
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const server = await startDemo(+(process.argv[2] || 8642));
  console.log('Demo vendor bill: http://127.0.0.1:' + server.address().port + '/');
  console.log('Press Ctrl+C to stop.');
}

