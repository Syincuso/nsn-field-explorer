/* Injects the field explorer into the page's MAIN world so it can call NetSuite's own
 * nlapi* functions. Running it again on the same tab closes the panel.
 * If the browser refuses to run it (for example on an edge:// or chrome:// page, or if the script
 * file is rejected), the toolbar button shows a red "!" and its tooltip says why, instead of
 * silently doing nothing.
 * Firefox runs this file as an event page (manifest background.scripts) and Chrome and Edge as a
 * service worker. Firefox's browser.* API always returns promises, which the calls below rely on. */
var TITLE = 'NSN Field Explorer';
var api = typeof browser !== 'undefined' && browser.scripting ? browser : chrome;

api.action.onClicked.addListener(function (tab) {
  if (!tab || !tab.id) return;
  return api.scripting.executeScript({
    target: { tabId: tab.id },
    files: ['ns-field-explorer.js'],
    world: 'MAIN'
  }).then(function () {
    return setState(tab.id, '', TITLE);
  }, function (err) {
    var msg = (err && err.message) || String(err);
    console.warn(TITLE + ' could not run on this tab: ' + msg);
    return setState(tab.id, '!', TITLE + ' could not run on this tab: ' + msg);
  });
});

function setState(tabId, badge, title) {
  var calls = [
    api.action.setBadgeText({ tabId: tabId, text: badge }),
    api.action.setTitle({ tabId: tabId, title: title })
  ];
  if (badge) calls.push(api.action.setBadgeBackgroundColor({ tabId: tabId, color: '#b22222' }));
  /* The tab may have closed in the meantime; that is not worth an error. */
  return Promise.all(calls).catch(function () {});
}

